import 'dart:math';
import 'package:flutter/material.dart';
import 'package:get/get.dart';
import '../models/quiz_question.dart';

enum ResultFilter { all, correct, incorrect }

class QuizResultScreen extends StatefulWidget {
  final List<QuizQuestion> questions;
  final Map<int, String> userAnswers;
  final String notes; // Notes already generated by backend

  const QuizResultScreen({
    super.key,
    required this.questions,
    required this.userAnswers,
    required this.notes,
  });

  @override
  State<QuizResultScreen> createState() => _QuizResultScreenState();
}

class _QuizResultScreenState extends State<QuizResultScreen> {
  ResultFilter activeFilter = ResultFilter.all;

  int get correctCount {
    int count = 0;
    for (int i = 0; i < widget.questions.length; i++) {
      if (widget.userAnswers[i] == widget.questions[i].answer) {
        count++;
      }
    }
    return count;
  }

  List<int> get filteredIndices {
    List<int> indices = [];
    for (int i = 0; i < widget.questions.length; i++) {
      final isCorrect = widget.userAnswers[i] == widget.questions[i].answer;
      if (activeFilter == ResultFilter.all) {
        indices.add(i);
      } else if (activeFilter == ResultFilter.correct && isCorrect) {
        indices.add(i);
      } else if (activeFilter == ResultFilter.incorrect && !isCorrect) {
        indices.add(i);
      }
    }
    return indices;
  }

  @override
  Widget build(BuildContext context) {
    final total = widget.questions.length;
    final score = correctCount;

    return Scaffold(
      backgroundColor: const Color(0xff141416),
      appBar: AppBar(
        backgroundColor: Colors.transparent,
        elevation: 0,
        leading: IconButton(
          icon: const Icon(Icons.arrow_back, color: Color(0xfff5c700)),
          onPressed: () => Get.back(),
        ),
        title: const Text(
          'ToolForge',
          style: TextStyle(
            color: Color(0xfff5c700),
            fontSize: 22,
            fontWeight: FontWeight.bold,
          ),
        ),
      ),
      body: SafeArea(
        child: Column(
          children: [
            Expanded(
              child: ListView(
                padding: const EdgeInsets.symmetric(horizontal: 20, vertical: 10),
                children: [
                  // Circular Score Ring
                  Center(
                    child: SizedBox(
                      width: 140,
                      height: 140,
                      child: CustomPaint(
                        painter: ScoreCirclePainter(
                          score: score,
                          total: total,
                        ),
                        child: Center(
                          child: RichText(
                            textAlign: TextAlign.center,
                            text: TextSpan(
                              children: [
                                TextSpan(
                                  text: '$score\n',
                                  style: const TextStyle(
                                    color: Color(0xffa6e22e),
                                    fontSize: 34,
                                    fontWeight: FontWeight.bold,
                                  ),
                                ),
                                TextSpan(
                                  text: '/$total',
                                  style: const TextStyle(
                                    color: Colors.white,
                                    fontSize: 16,
                                    fontWeight: FontWeight.w600,
                                  ),
                                ),
                              ],
                            ),
                          ),
                        ),
                      ),
                    ),
                  ),
                  const SizedBox(height: 28),

                  // Filter Pills: All | Correct | Incorrect
                  Row(
                    mainAxisAlignment: MainAxisAlignment.center,
                    children: [
                      _buildFilterPill('All', ResultFilter.all),
                      const SizedBox(width: 10),
                      _buildFilterPill('Correct', ResultFilter.correct),
                      const SizedBox(width: 10),
                      _buildFilterPill('Incorrect', ResultFilter.incorrect),
                    ],
                  ),
                  const SizedBox(height: 24),

                  // Filtered Question Cards
                  ...filteredIndices.map((idx) {
                    final q = widget.questions[idx];
                    final userChoice = widget.userAnswers[idx];

                    return Container(
                      margin: const EdgeInsets.only(bottom: 18),
                      decoration: BoxDecoration(
                        color: const Color(0xff1f1f23),
                        borderRadius: BorderRadius.circular(18),
                        border: Border.all(
                          color: const Color(0xfff5c700),
                          width: 1.5,
                        ),
                      ),
                      child: Stack(
                        clipBehavior: Clip.none,
                        children: [
                          // Number Badge top-left
                          Positioned(
                            top: -1,
                            left: -1,
                            child: Container(
                              padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 6),
                              decoration: const BoxDecoration(
                                color: Color(0xfff5c700),
                                borderRadius: BorderRadius.only(
                                  topLeft: Radius.circular(18),
                                  bottomRight: Radius.circular(14),
                                ),
                              ),
                              child: Text(
                                '${idx + 1}.',
                                style: const TextStyle(
                                  color: Colors.black,
                                  fontSize: 15,
                                  fontWeight: FontWeight.bold,
                                ),
                              ),
                            ),
                          ),

                          Padding(
                            padding: const EdgeInsets.fromLTRB(16, 36, 16, 16),
                            child: Column(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              children: [
                                Text(
                                  q.question,
                                  style: const TextStyle(
                                    color: Colors.white,
                                    fontSize: 15,
                                    fontWeight: FontWeight.w600,
                                    height: 1.35,
                                  ),
                                ),
                                const SizedBox(height: 14),

                                // Options List with Result Tags
                                ...q.options.map((opt) {
                                  final isAnswer = opt == q.answer;
                                  final isChosen = opt == userChoice;

                                  return Padding(
                                    padding: const EdgeInsets.symmetric(vertical: 4),
                                    child: Row(
                                      mainAxisAlignment: MainAxisAlignment.spaceBetween,
                                      children: [
                                        Expanded(
                                          child: Text(
                                            opt,
                                            style: const TextStyle(
                                              color: Colors.white70,
                                              fontSize: 14,
                                            ),
                                          ),
                                        ),
                                        if (isAnswer)
                                          const Text(
                                            'Correct',
                                            style: TextStyle(
                                              color: Color(0xff00e676),
                                              fontWeight: FontWeight.bold,
                                              fontSize: 13,
                                            ),
                                          )
                                        else if (isChosen && !isAnswer)
                                          const Text(
                                            'You Chose',
                                            style: TextStyle(
                                              color: Color(0xffff3d00),
                                              fontWeight: FontWeight.bold,
                                              fontSize: 13,
                                            ),
                                          ),
                                      ],
                                    ),
                                  );
                                }),
                              ],
                            ),
                          ),
                        ],
                      ),
                    );
                  }),
                ],
              ),
            ),

            // Bottom "Generate Notes" Button
            Padding(
              padding: const EdgeInsets.symmetric(horizontal: 20, vertical: 12),
              child: SizedBox(
                width: double.infinity,
                height: 52,
                child: ElevatedButton(
                  style: ElevatedButton.styleFrom(
                    backgroundColor: const Color(0xfff5c700),
                    shape: RoundedRectangleBorder(
                      borderRadius: BorderRadius.circular(28),
                    ),
                    elevation: 2,
                  ),
                  onPressed: () {
                    // Opens the Study Notes viewer
                    _showNotesSheet(context, widget.notes);
                  },
                  child: const Text(
                    'Generate Notes',
                    style: TextStyle(
                      color: Colors.black,
                      fontSize: 17,
                      fontWeight: FontWeight.bold,
                    ),
                  ),
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildFilterPill(String title, ResultFilter filter) {
    final isSelected = activeFilter == filter;
    return GestureDetector(
      onTap: () => setState(() => activeFilter = filter),
      child: Container(
        padding: const EdgeInsets.symmetric(horizontal: 22, vertical: 8),
        decoration: BoxDecoration(
          color: isSelected ? const Color(0xff2a2a30) : Colors.transparent,
          borderRadius: BorderRadius.circular(20),
          border: Border.all(
            color: isSelected ? const Color(0xfff5c700) : Colors.white30,
            width: 1.4,
          ),
        ),
        child: Text(
          title,
          style: TextStyle(
            color: isSelected ? Colors.white : Colors.white60,
            fontWeight: FontWeight.w600,
            fontSize: 13,
          ),
        ),
      ),
    );
  }

  void _showNotesSheet(BuildContext context, String notes) {
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: const Color(0xff18181c),
      shape: const RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(top: Radius.circular(22)),
      ),
      builder: (ctx) => DraggableScrollableSheet(
        initialChildSize: 0.7,
        minChildSize: 0.4,
        maxChildSize: 0.95,
        expand: false,
        builder: (_, scrollController) => Padding(
          padding: const EdgeInsets.all(20),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Center(
                child: Container(
                  width: 40,
                  height: 4,
                  decoration: BoxDecoration(
                    color: Colors.white24,
                    borderRadius: BorderRadius.circular(2),
                  ),
                ),
              ),
              const SizedBox(height: 16),
              const Text(
                'Study Notes & Summary',
                style: TextStyle(
                  color: Color(0xfff5c700),
                  fontSize: 20,
                  fontWeight: FontWeight.bold,
                ),
              ),
              const Divider(color: Colors.white24, height: 24),
              Expanded(
                child: SingleChildScrollView(
                  controller: scrollController,
                  child: Text(
                    notes.isNotEmpty ? notes : 'No notes generated for this session.',
                    style: const TextStyle(
                      color: Colors.white,
                      fontSize: 14,
                      height: 1.5,
                    ),
                  ),
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}

// Custom Painter for the Yellow/Green Score Gauge
class ScoreCirclePainter extends CustomPainter {
  final int score;
  final int total;

  ScoreCirclePainter({required this.score, required this.total});

  @override
  void paint(Canvas canvas, Size size) {
    final center = Offset(size.width / 2, size.height / 2);
    final radius = size.width / 2 - 10;
    const strokeWidth = 9.0;

    // Track Background
    final bgPaint = Paint()
      ..color = const Color(0xff29292e)
      ..style = PaintingStyle.stroke
      ..strokeWidth = strokeWidth;

    canvas.drawCircle(center, radius, bgPaint);

    // Progress Arc
    final progressPaint = Paint()
      ..color = const Color(0xffa6e22e)
      ..style = PaintingStyle.stroke
      ..strokeWidth = strokeWidth
      ..strokeCap = StrokeCap.round;

    final sweepAngle = total > 0 ? (score / total) * 2 * pi : 0.0;
    canvas.drawArc(
      Rect.fromCircle(center: center, radius: radius),
      -pi / 2,
      sweepAngle,
      false,
      progressPaint,
    );
  }

  @override
  bool shouldRepaint(covariant CustomPainter oldDelegate) => true;
}